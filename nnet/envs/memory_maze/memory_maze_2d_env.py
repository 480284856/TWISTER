# Memory Maze 2D: grid world version of Memory Maze
#
# The maze layout and the target positions are generated by the memory_maze package (same maze distribution as the
# 3D task, global observables), then the agent moves on the grid: 5 discrete actions (noop, left, right, up, down),
# no physics simulation after the reset.
#
# Observation: 5x5 egocentric view, the 3x3 cells around the agent (walls black, free cells white, targets in their
# color) surrounded by a border of the current target color, upscaled to img_size with nearest interpolation.
# Reward 1 when the agent enters the current target cell, a new (different) target is then drawn.
# Episodes only end with the time limit: is_last = 1 and done = 0.

# PyTorch
import torch
import torchvision

# NeuralNets
from nnet.structs import AttrDict

# Other
import os
import sys
import random
import logging
import datetime
from collections import deque


# memory_maze resets the agent with a velocity although it has no free joint (harmless absl warning at every reset)
class _NoFreeJointVelocityFilter(logging.Filter):
    def filter(self, record):
        return "Cannot set velocity on Entity with no free joint" not in record.getMessage()


logging.getLogger("absl").addFilter(_NoFreeJointVelocityFilter())


class MemoryMaze2dEnv:

    """

    actions: 5
        0: noop
        1: left
        2: right
        3: up
        4: down

    """

    # Episode length (agent steps) per maze size, same as the 3D task
    EPISODE_LENGTHS = {9: 1000, 11: 2000, 13: 3000, 15: 4000}

    # action: (dx, dy)
    MOVES = {0: (0, 0), 1: (-1, 0), 2: (1, 0), 3: (0, -1), 4: (0, 1)}

    COLORS = [
        [255, 0, 0],
        [0, 255, 0],
        [0, 0, 255],
        [255, 0, 255],
        [255, 255, 0],
        [0, 255, 255],
    ]

    num_actions = 5

    def obs_space(self):

        return (["image", (3, self.img_size[0], self.img_size[1]), torch.uint8],)

    def __init__(
            self,
            maze_size=15,
            img_size=(64, 64),
            history_frames=1,
            episode_saving_path=None,
            action_repeat=1,
            seed=None,
            camera_resolution=16
        ):

        assert maze_size in self.EPISODE_LENGTHS, "maze_size must be one of {}".format(list(self.EPISODE_LENGTHS))
        assert history_frames == 1, "history_frames > 1 not supported"
        assert action_repeat == 1, "action_repeat must be 1"

        # memory_maze defaults to MUJOCO_GL=egl (headless GPU rendering on Linux), not available on macOS
        if sys.platform == "darwin" and "MUJOCO_GL" not in os.environ:
            os.environ["MUJOCO_GL"] = "glfw"

        self.maze_size = maze_size
        self.img_size = tuple(img_size)
        self.history_frames = history_frames
        self.action_repeat = action_repeat
        self.episode_length = self.EPISODE_LENGTHS[maze_size]
        # The 3D task is only used to generate mazes at reset: render at a small resolution
        self.camera_resolution = camera_resolution
        self.set_seed(seed if seed is not None else random.randint(0, 2**31 - 1))

        # episode_saving_path
        self.episode_saving_path = episode_saving_path
        if self.episode_saving_path is not None:
            os.makedirs(self.episode_saving_path, exist_ok=True)

        self.fps = 2

    def set_seed(self, seed):

        # Imported here so that the other environments do not require memory_maze
        from memory_maze import tasks

        # global_observables: maze_layout, agent_pos, targets_pos (same as the gym MemoryMaze-<n>x<n>-ExtraObs-v0 envs)
        self.env = getattr(tasks, "memory_maze_{}x{}".format(self.maze_size, self.maze_size))(
            seed=seed,
            camera_resolution=self.camera_resolution,
            global_observables=True,
            image_only_obs=False
        )
        self.generator = torch.Generator().manual_seed(seed)

    def random_seed(self):
        self.set_seed(random.randint(0, 2**31 - 1))

    def sample(self):

        return torch.nn.functional.one_hot(torch.randint(low=0, high=self.num_actions, size=()), num_classes=self.num_actions).type(torch.float32)

    def is_free(self, x, y):

        # maze_layout has a one cell wall border: grid (x, y) -> layout [1 + y, 1 + x]
        return bool(self.maze_layout[:, 1 + y, 1 + x].any())

    def best(self):

        """Expert action: first action of a shortest path to the current target (BFS), one hot"""

        start = tuple(self.pos)
        goal = tuple(self.targets_pos[self.target_id])
        visited = {start}
        queue = deque([(start, None)])
        while queue:
            (x, y), first_action = queue.popleft()
            for action in (1, 2, 3, 4):
                dx, dy = self.MOVES[action]
                next_pos = (x + dx, y + dy)
                if next_pos in visited or not self.is_free(*next_pos):
                    continue
                visited.add(next_pos)
                next_first_action = action if first_action is None else first_action
                if next_pos == goal:
                    return torch.nn.functional.one_hot(torch.tensor(next_first_action), num_classes=self.num_actions).type(torch.float32)
                queue.append((next_pos, next_first_action))

        # Unreachable target
        return torch.nn.functional.one_hot(torch.tensor(0), num_classes=self.num_actions).type(torch.float32)

    def get_obs(self):

        # Border: current target color
        obs = torch.tensor(self.COLORS[self.target_id], dtype=torch.uint8)[:, None, None].repeat(1, 5, 5)

        # 3x3 cells around the agent (agent at layout [1 + y, 1 + x])
        obs[:, 1:-1, 1:-1] = self.maze_layout[:, self.pos[1]:self.pos[1] + 3, self.pos[0]:self.pos[0] + 3]

        # Resize Obs
        obs = torchvision.transforms.functional.resize(obs, size=list(self.img_size), interpolation=torchvision.transforms.InterpolationMode.NEAREST)

        return obs

    def get_new_target_id(self):

        target_id = int(torch.randint(0, len(self.targets_pos) - 1, (), generator=self.generator))
        return target_id + int(target_id >= self.target_id)

    def reset(self):

        # Reset Env (new maze)
        state = self.env.reset().observation

        # Agent / targets grid positions (x, y)
        self.pos = [int(state["agent_pos"][0]), int(state["agent_pos"][1])]
        self.targets_pos = [[int(x), int(y)] for x, y in state["targets_pos"]]

        # Maze layout (1 = free, 0 = wall) -> uint8 RGB, targets colored
        layout = 255 * torch.as_tensor(state["maze_layout"].copy(), dtype=torch.uint8).unsqueeze(dim=0).repeat(3, 1, 1)
        assert len(self.targets_pos) <= len(self.COLORS)
        for color, (x, y) in zip(self.COLORS, self.targets_pos):
            assert (layout[:, y, x] == 255).all(), "target {} not on a free cell".format((x, y))
            layout[:, y, x] = torch.tensor(color, dtype=torch.uint8)

        # Add Walls
        self.maze_layout = torch.zeros((3, layout.shape[1] + 2, layout.shape[2] + 2), dtype=torch.uint8)
        self.maze_layout[:, 1:-1, 1:-1] = layout

        # Set Current Target
        self.target_id = int(torch.randint(0, len(self.targets_pos), (), generator=self.generator))

        obs = self.get_obs()

        # Episode Score / videos
        self.episode_score = 0.0
        if self.episode_saving_path is not None:
            self.episode_video = [obs.permute(1, 2, 0)]

        return AttrDict(
            state=obs,
            reward=torch.tensor(0.0, dtype=torch.float32),
            done=torch.tensor(False, dtype=torch.float32),
            is_first=torch.tensor(True, dtype=torch.float32),
            is_last=torch.tensor(False, dtype=torch.float32)
        )

    def step(self, action):

        action = int(action.item()) if torch.is_tensor(action) else int(action)
        assert action in self.MOVES, "Possible actions are 0 (noop), 1 (move left), 2 (move right), 3 (move up) and 4 (move down). Received {}.".format(action)

        reward = 0.0
        dx, dy = self.MOVES[action]
        if action != 0 and self.is_free(self.pos[0] + dx, self.pos[1] + dy):

            # Update Position
            self.pos = [self.pos[0] + dx, self.pos[1] + dy]

            # Check if target pos
            if self.pos == self.targets_pos[self.target_id]:
                self.target_id = self.get_new_target_id()
                reward = 1.0

        obs = self.get_obs()

        # Update Episode Score / videos (is_last is set by the TimeLimit wrapper, the video is saved at episode_length)
        self.episode_score += reward
        if self.episode_saving_path is not None:
            self.episode_video.append(obs.permute(1, 2, 0))
            if len(self.episode_video) == self.episode_length + 1:
                date_time_score = str(datetime.datetime.now()).replace(" ", "_") + "_" + str(self.episode_score)
                torchvision.io.write_video(filename=os.path.join(self.episode_saving_path, "{}.mp4".format(date_time_score)), video_array=torch.stack(self.episode_video, dim=0), fps=self.fps, video_codec="libx264")

        return AttrDict(
            state=obs,
            reward=torch.tensor(reward, dtype=torch.float32),
            done=torch.tensor(False, dtype=torch.float32),
            is_first=torch.tensor(False, dtype=torch.float32),
            is_last=torch.tensor(False, dtype=torch.float32)
        )
